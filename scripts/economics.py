"""Measured unit economics from the state DB (+ labelled assumptions).  python scripts/economics.py"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from paperci import db, ledger  # noqa: E402
from paperci.stats import funnel  # noqa: E402

# Assumption (not measured): a 4 vCPU / 8 GB cloud worker (e.g. AWS c6i.xlarge on-demand, us-east-1)
# at ~$0.17/hour. Sandbox time is measured; the hourly price is not.
CPU_HOUR_USD = 0.17

f = funnel()
builds = [json.loads(r["output"]) for r in db.q("SELECT output FROM stages WHERE stage='build' AND status='done'")]
verifies = [json.loads(r["output"]) for r in db.q("SELECT output FROM stages WHERE stage='robustness' AND status='done'")]
oracles = [json.loads(r["output"]) for r in db.q("SELECT output FROM stages WHERE stage='oracle' AND status='done'")]
build_min = sum(b.get("seconds", 0) for b in builds) / 60
verify_min = sum(r["seconds"] for v in verifies for r in v.get("runs", [])) / 60
oracle_min = sum(o.get("seconds", 0) for o in oracles) / 60
n_att = len(builds)
spend = ledger.local_total()
by_stage = {r["stage"]: round(r["c"], 4) for r in db.q("SELECT stage, SUM(cost_usd) c FROM spend GROUP BY stage")}
live = {(r["arxiv_id"], r["run_label"]) for r in db.q("SELECT arxiv_id, run_label, output FROM stages WHERE stage='package' "
                                                        "AND status='done'") if json.loads(r["output"]).get("task_id")}
validated = sum(1 for r in db.q("SELECT arxiv_id, run_label, output FROM stages WHERE stage='oracle' AND status='done'")
                if json.loads(r["output"]).get("reward", 0) >= 0.999 and (r["arxiv_id"], r["run_label"]) in live)
built = sum(1 for b in builds if b.get("status") == "built")
measured = sum(1 for r in db.q("SELECT output FROM stages WHERE stage='verdict' AND status='done'")
               if any(pc.get("comparison") for pc in json.loads(r["output"]).get("per_claim", {}).values()))
out = {
    "measured": {
        "papers_watched": f["watched_with_code"], "triage_accept": f["triage_accept"],
        "papers_with_sealed_claims": f["claims_extracted"], "build_attempts": n_att, "built": built,
        "metric_measured_offline": measured, "oracle_validated_tasks": validated,
        "llm_spend_total_usd": round(spend, 4), "llm_spend_by_stage_usd": by_stage,
        "front_half_cost_per_watched_paper_usd": round(f["front_half_cost_usd"] / max(f["watched_with_code"], 1), 5),
        "builder_cost_per_attempt_usd": round(by_stage.get("builder", 0) / max(n_att, 1), 4),
        "sandbox_minutes_total": round(build_min + verify_min + oracle_min, 1),
        "sandbox_minutes_per_attempt": round((build_min + verify_min) / max(n_att, 1), 2),
        "llm_cost_per_validated_task_all_in_usd": round(spend / validated, 3) if validated else None,
        "remote_spend_reported_by_proxy_usd": round(ledger.remote_spend(0), 4),
    },
    "assumptions": {"cpu_hour_usd": CPU_HOUR_USD,
                    "compute_cost_per_attempt_usd": round((build_min + verify_min) / max(n_att, 1) / 60 * CPU_HOUR_USD, 4)},
}
print(json.dumps(out, indent=1))

if "--md" in sys.argv:
    from paperci.stats import label_stats
    m, a = out["measured"], out["assumptions"]
    h1, h2 = label_stats("heldout-v1"), label_stats("heldout-v2")
    llm_v2 = h2["cost_per_attempt"] or 0
    cogs = llm_v2 + a["compute_cost_per_attempt_usd"] + m["front_half_cost_per_watched_paper_usd"] * m["papers_watched"] / max(m["triage_accept"], 1)
    v2_task = (h2["llm_cost_usd"] / h2["oracle_validated"]) if h2["oracle_validated"] else None
    L = ["# Unit economics (generated by `python scripts/economics.py --md`)", "",
         "Everything under **Measured** comes from the spend ledger (reconciled with the LiteLLM proxy's own",
         "`/key/info` spend) and the state DB. Everything under **Assumptions** is labelled as such.", "",
         "## Measured (whole hackathon, dev + held-out + tuning)", "",
         "| quantity | value |", "|---|---|",
         *[f"| {k} | {v} |" for k, v in m.items() if k != "llm_spend_by_stage_usd"],
         f"| llm_spend_by_stage_usd | {m['llm_spend_by_stage_usd']} |", "",
         "## Measured per held-out attempt (same 5 papers, v1 baseline vs v2 self-improved builder)", "",
         "| | heldout-v1 | heldout-v2 |", "|---|---|---|",
         f"| attempts | {h1['papers_attempted']} | {h2['papers_attempted']} |",
         f"| built | {h1['built']} | {h2['built']} |",
         f"| integrity-flagged (replay / no repo code path) | {h1['integrity_flagged']} | {h2['integrity_flagged']} |",
         f"| oracle-validated tasks | {h1['oracle_validated']} | {h2['oracle_validated']} |",
         f"| LLM $ per attempt (builder+verifier+solver) | {h1['cost_per_attempt']} | {h2['cost_per_attempt']} |",
         f"| avg builder turns | {h1['avg_builder_turns']} | {h2['avg_builder_turns']} |",
         f"| avg build minutes | {h1['avg_build_minutes']} | {h2['avg_build_minutes']} |",
         f"| LLM $ per validated task | {h1['cost_per_validated_task']} | {h2['cost_per_validated_task']} |", "",
         "## Assumptions (not measured)", "",
         f"- CPU worker price: ${a['cpu_hour_usd']}/hour (4 vCPU / 8 GB on-demand class). Sandbox minutes are measured;",
         f"  the price is not. Compute per attempt at that price: ${a['compute_cost_per_attempt_usd']}.",
         "- No GPU work is included: GPU-scale papers are rejected at triage today.",
         "- LLM prices are the proxy's list prices (`/v1/model/info`), with Claude prompt caching on the builder.", "",
         "## Derived COGS (measured LLM + assumed compute)", "",
         f"- COGS per build attempt (v2): about ${cogs:.3f} (LLM {llm_v2} + compute {a['compute_cost_per_attempt_usd']} +"
         " the front-half triage/claims cost spread over accepted papers).",
         f"- LLM cost per validated task on held-out v2: {('$' + format(v2_task, '.2f')) if v2_task else 'n/a'} (only "
         f"{h2['oracle_validated']} validated task(s), so this is a small-sample number).",
         f"- All-in LLM spend per validated task including all development/tuning runs: ${m['llm_cost_per_validated_task_all_in_usd']}.", "",
         "## cfo.ai entry sheet (for the human; prices are hypotheses to test, not measured demand)", "",
         "| field | value | source |", "|---|---|---|",
         f"| COGS per reproduction attempt | ${cogs:.2f} | measured LLM + assumed compute |",
         f"| Attempts per validated task (held-out v2) | {round(h2['papers_attempted'] / h2['oracle_validated'], 1) if h2['oracle_validated'] else 'n/a'} | measured, n=5 |",
         "| Product A: verified agent tasks (per task, labs/eval teams) | $50-150 per validated task | hypothesis |",
         "| Product B: \"CI badge\" for paper authors/venues | $0 free tier, $49/month lab plan | hypothesis |",
         "| Product C: reproducibility audit for a venue/track | $2-5k per track | hypothesis |",
         "| Infra fixed cost | $300/month (orchestrator VM, storage, tracing) | assumption |",
         "| Headcount | 2 founders, no salary first 6 months | assumption |",
         "| Buyer list | docs/buyer-map.md (Crustdata company enrichment) | measured enrichment |", ""]
    (Path(__file__).resolve().parent.parent / "docs" / "unit-economics.md").write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print("wrote docs/unit-economics.md")
